function ErrorComponent({ error, reset }: ErrorComponentProps) {
  console.error(error);
  const router = useRouter();

  return (
    <div className="flex min-h-[70vh] items-center justify-center bg-background px-4">
      <div className="max-w-md text-center">
        <h1 className="serif-title text-2xl">This page didn't load</h1>
        <p className="mt-2 text-sm text-muted-foreground">
          Something went wrong on our end. You can try refreshing or head back home.
        </p>
        <div className="mt-6 flex flex-wrap justify-center gap-2">
          <button
            onClick={() => {
              router.invalidate();
              reset();
            }}
            className="label-xs inline-flex h-11 items-center justify-center bg-ink px-8 text-ink-foreground"
          >
            Try again
          </button>
          <a
            href="/"
            className="label-xs inline-flex h-11 items-center justify-center border border-ink px-8"
          >
            Go home
          </a>
        </div>
      </div>
    </div>
  );
}

